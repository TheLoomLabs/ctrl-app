#!/bin/sh
# SPDX-License-Identifier: GPL-2.0-only
#
# Prints expected acceleration gains computed by the real firmware code, as
# TypeScript for src/lib/gyro_accel.golden.ts. Usage:
#
#   sh scripts/accel_golden.sh ../alpakka_firmware > src/lib/gyro_accel.golden.ts
#
# It extracts gyro_accel_shape() and gyro_accel_gain() from the firmware's
# src/gyro.c, compiles them for the host and evaluates them for every case in
# CASES below. The app tests (gyro_accel.spec.ts) compare lib/gyro_accel.ts
# against this output, so the app graph always matches the controller.

set -e
FW=${1:?usage: accel_golden.sh <path to alpakka_firmware>}
CC=${CC:-cc}
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

cat > "$TMP/main.c" <<'EOF'
#include <math.h>
#include <stdio.h>

typedef enum { GYRO_ACCEL_OFF, GYRO_ACCEL_LINEAR, GYRO_ACCEL_POWER,
               GYRO_ACCEL_NATURAL, GYRO_ACCEL_SIGMOID } GyroAccelCurve;
typedef struct { GyroAccelCurve curve; float gain_min, gain_max, threshold,
                 speed_max, exponent, smoothing; } GyroAccel;
EOF
# Copy both functions verbatim from the firmware (from the shape function
# up to the closing brace of the gain function).
sed -n '/^static float gyro_accel_shape(/,/^float gyro_accel_gain(/p' "$FW/src/gyro.c" \
    | sed '$d' >> "$TMP/main.c"
sed -n '/^float gyro_accel_gain(/,/^}/p' "$FW/src/gyro.c" >> "$TMP/main.c"
cat >> "$TMP/main.c" <<'EOF'

// Curve parameters as raw profile bytes (curve, gain_min, gain_max, threshold,
// speed_max, exponent), converted like profile.c does.
static const int CASES[][6] = {
    {0, 100, 30, 30, 75, 20},   // Off.
    {1, 100, 30, 30, 75, 0},    // Linear.
    {2, 100, 60, 40, 100, 15},  // Power (Flick turns preset).
    {2, 100, 40, 25, 100, 0},   // Power, default exponent.
    {3, 100, 20, 20, 75, 30},   // Natural (Subtle preset).
    {3, 120, 50, 10, 50, 0},    // Natural, default exponent.
    {4, 100, 30, 30, 80, 80},   // Sigmoid (Balanced preset).
    {4, 70, 40, 25, 75, 100},   // Sigmoid (Precision + flick preset).
    {4, 100, 55, 50, 80, 100},  // Sigmoid flick (guide).
    {4, 100, 30, 50, 25, 100},  // Full gain speed below threshold.
    {1, 0, 0, 0, 0, 0},         // All zero bytes (stock profile).
};
static const float SPEEDS[] = {0, 10, 30, 60, 100, 150, 200, 250, 300, 400, 500, 570, 1000};

int main(void) {
    int nc = sizeof(CASES) / sizeof(CASES[0]);
    int ns = sizeof(SPEEDS) / sizeof(SPEEDS[0]);
    printf("// Generated by scripts/accel_golden.sh from the firmware's src/gyro.c.\n");
    printf("// Do not edit by hand.\n\n");
    printf("export const ACCEL_SPEEDS = [");
    for (int s = 0; s < ns; s++) printf("%s%g", s ? ", " : "", SPEEDS[s]);
    printf("]\n\nexport const ACCEL_GOLDEN: {bytes: number[], gains: number[]}[] = [\n");
    for (int c = 0; c < nc; c++) {
        const int *b = CASES[c];
        GyroAccel a = {
            .curve = b[0],
            .gain_min = (b[1] ? b[1] : 100) / 100.0f,
            .gain_max = (b[2] ? b[2] : 10) / 10.0f,
            .threshold = b[3] * 2.0f,
            .speed_max = b[4] * 4.0f,
            .exponent = b[5] / 10.0f,
        };
        printf("  {bytes: [%d, %d, %d, %d, %d, %d], gains: [", b[0], b[1], b[2], b[3], b[4], b[5]);
        for (int s = 0; s < ns; s++) printf("%s%.6f", s ? ", " : "", gyro_accel_gain(&a, SPEEDS[s]));
        printf("]},\n");
    }
    printf("]\n");
    return 0;
}
EOF
$CC -std=c11 -Wall -Werror -O1 -o "$TMP/golden" "$TMP/main.c" -lm
"$TMP/golden"
